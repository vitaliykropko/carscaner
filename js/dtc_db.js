/**
 * Расшифровывает любой код ошибки OBD-II / EOBD по стандартам SAE J2019 / ISO 15031-6,
 * если точного совпадения нет в базе.
 */
export function decodeDtc(code) {
  if (!code || typeof code !== 'string') return null;
  const cleanCode = code.trim().toUpperCase();

  // Если код найден в нашей базе
  if (DTC_DATABASE[cleanCode]) {
    return {
      code: cleanCode,
      ...DTC_DATABASE[cleanCode]
    };
  }

  // Расшифровка структуры кода по стандарту
  const firstChar = cleanCode.charAt(0);
  const secondChar = cleanCode.charAt(1);
  const thirdChar = cleanCode.charAt(2);

  let system = 'Неизвестная система';
  if (firstChar === 'P') system = 'Двигатель / Трансмиссия (Powertrain)';
  else if (firstChar === 'C') system = 'Шасси / Тормоза / Подвеска (Chassis)';
  else if (firstChar === 'B') system = 'Кузов / Электроника салона (Body)';
  else if (firstChar === 'U') system = 'Сетевые коммуникации / Шина CAN (Network)';

  let type = secondChar === '0' || secondChar === '2' ? 'Стандартный код OBD-II (SAE)' : 'Специфический код производителя (Mazda / Ford)';

  let subsystem = '';
  if (firstChar === 'P') {
    switch (thirdChar) {
      case '1':
      case '2':
        subsystem = 'Топливная система или измерение расхода воздуха';
        break;
      case '3':
        subsystem = 'Система зажигания или пропуски воспламенения';
        break;
      case '4':
        subsystem = 'Вспомогательный контроль токсичности (катализатор, продувка, EGR)';
        break;
      case '5':
        subsystem = 'Контроль скорости автомобиля и оборотов холостого хода';
        break;
      case '6':
        subsystem = 'Внутренние цепи блока управления (ECM/PCM) или выходы';
        break;
      case '7':
      case '8':
      case '9':
        subsystem = 'Трансмиссия / Коробка передач (АКПП/МКПП)';
        break;
      default:
        subsystem = 'Общая система управления двигателем';
    }
  }

  return {
    code: cleanCode,
    title: `${system}: ${type}`,
    module: system.split(' ')[0],
    subsystem: subsystem,
    severity: 'warning',
    causes: ['Требуется дополнительная диагностика специализированным дилерским сканером'],
    hint: `Код ${cleanCode} относится к категории: ${subsystem || system}.`
  };
}
